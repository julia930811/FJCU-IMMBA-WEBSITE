function locale() {
  return document.documentElement.lang.startsWith("zh") ? "zh" : "en";
}
function t() { return I18N[locale()]; }
function currentFile() {
  const page = document.body.dataset.page;
  return page === "index" ? "index.html" : page + ".html";
}

function isActive(href) {
  const [file, hash] = href.split("#");
  if (currentFile() !== file) return false;
  if (hash) return location.hash === "#" + hash;
  return true;
}

function logoMark() {
  const src = (locale() === "zh" ? "img/logo.png" : "../img/logo.png") + "?v=6";
  return `<img class="brand-mark" src="${src}" alt="imMBA">`;
}

function adminSwitch() {
  const zh = locale() === "zh";
  const page = document.body.dataset.page;
  const Auth = window.IMMBAAuth || {};
  const superLink = Auth.isSuper && Auth.isSuper()
    ? `<a href="admin-users.html" class="${page === "admin-users" ? "is-active" : ""}">${zh ? "帳號審核" : "Approve admins"}</a>`
    : "";
  return `<nav class="admin-switch" aria-label="${zh ? "後台分頁" : "Back office"}">
    <a href="admin-news.html" class="${page === "admin-news" ? "is-active" : ""}">${zh ? "公告後台" : "AdminNews"}</a>
    <a href="admin-faculty.html" class="${page === "admin-faculty" ? "is-active" : ""}">${zh ? "師資後台" : "AdminFaculty"}</a>
    <a href="admin-alumni.html" class="${page === "admin-alumni" ? "is-active" : ""}">${zh ? "校友後台" : "AdminAlumni"}</a>
    ${superLink}
  </nav>`;
}

function authActionHTML() {
  const L = t();
  const Auth = window.IMMBAAuth;
  if (!Auth || !Auth.user || !Auth.user()) {
    return `<a class="btn btn-line" href="login.html">${L.authLogin}</a>`;
  }
  const mail = (Auth.user().email || L.authAccount).split("@")[0];
  return `<a class="auth-chip" href="account.html">${mail}</a>
    ${Auth.canEdit() ? `<a class="btn btn-line" href="admin-faculty.html">${L.authBackOffice}</a>` : ""}`;
}

function navLink(href, label) {
  return `<a href="${href}" class="${isActive(href) ? "is-active" : ""}">${label}</a>`;
}

function navItem(item) {
  const parentOn = currentFile() === item.href;
  const blank = href => href.startsWith("http") ? ` target="_blank" rel="noopener"` : "";
  if (!item.children) return navLink(item.href, item.label);
  return `<div class="nav-item has-dropdown">
    <a href="${item.href}" class="nav-parent ${parentOn ? "is-active" : ""}" aria-haspopup="true"${blank(item.href)}>${item.label}</a>
    <div class="dropdown" role="menu">
      ${item.children.map(([href, label]) => `<a href="${href}" role="menuitem" class="${isActive(href) ? "is-active" : ""}"${blank(href)}>${label}</a>`).join("")}
    </div>
  </div>`;
}

