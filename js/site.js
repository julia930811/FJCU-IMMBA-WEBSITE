function liveNews() {
  return window.NewsStore ? window.NewsStore.published() : window.IMMBA.news;
}
function newsDetailHref(n) {
  return "news-detail.html?id=" + encodeURIComponent(n.id);
}
function newsPhoto(n, cls) {
  const src = (n.imageUrl || "").trim();
  if (!src) return "";
  return `<img class="${cls}" src="${src}" alt="" referrerpolicy="no-referrer">`;
}
function newsCard(n) {
  const photo = newsPhoto(n, "news-card-photo");
  return `
    <a class="news-card${photo ? " has-photo" : ""}" href="${newsDetailHref(n)}">
      ${photo}
      <div class="news-card-copy">
        <time>${n.date.replaceAll("-", "/")}</time>
        <h3>${n.pinned ? `<span class="tag">TOP</span>` : ""}${locale()==="zh"?n.zhTitle:n.enTitle}</h3>
      </div>
      <span class="news-more">${t().viewDetails} →</span>
    </a>
  `;
}
function newsItems(limit) {
  const list = liveNews();
  return (limit ? list.slice(0, limit) : list).map(newsCard).join("");
}

function newsSource() {
  const url = "https://www.management.fju.edu.tw/subweb/immba/news.php";
  return `<p class="news-source">${t().newsSource}：<a href="${url}" target="_blank" rel="noopener">${url}</a></p>`;
}

function officialBtn(url) {
  return `<p><a class="btn btn-line" href="${url}" target="_blank" rel="noopener">${locale()==="zh"?"官網原文頁":"Official page"}</a></p>`;
}

function fileKind(href) {
  const u = decodeURIComponent(href || "").toLowerCase();
  if (/\.pdf(\?|#|$)/.test(u)) return { key: "pdf", label: "PDF" };
  if (/\.docx?(\?|#|$)/.test(u)) return { key: "doc", label: "Word" };
  if (/\.xlsx?(\?|#|$)/.test(u)) return { key: "xls", label: "Excel" };
  if (/\.pptx?(\?|#|$)/.test(u)) return { key: "ppt", label: "PPT" };
  if (/\.(zip|rar|7z)(\?|#|$)/.test(u)) return { key: "zip", label: "ZIP" };
  return { key: "web", label: "WEB" };
}

function fileRow(href, label) {
  const k = fileKind(href);
  return `<a class="news-item file-item" href="${href}" target="_blank" rel="noopener">
    <span class="file-icon file-${k.key}" title="${k.label}"><b>${k.label}</b></span>
    <span>${label}</span>
    <span aria-hidden="true">↓</span>
  </a>`;
}

