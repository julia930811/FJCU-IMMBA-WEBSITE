-- Accountability: who changed what, when, and to which record.
create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid,
  actor_email text,
  action text not null,
  entity text not null,
  entity_id text,
  summary text,
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz default now()
);

create or replace function public.write_audit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  eid text;
  mail text;
  summary text;
  before_j jsonb;
  after_j jsonb;
begin
  if tg_table_name = 'profiles' and tg_op = 'UPDATE' and old.role is not distinct from new.role then
    return new;
  end if;
  if tg_op = 'DELETE' then
    eid := old.id::text;
    before_j := to_jsonb(old);
    after_j := null;
  else
    eid := new.id::text;
    after_j := to_jsonb(new);
    before_j := case when tg_op = 'UPDATE' then to_jsonb(old) else null end;
  end if;
  select p.email into mail from public.profiles p where p.id = auth.uid();
  if tg_table_name = 'faculty' then
    summary := coalesce(coalesce(new.zh_name, old.zh_name), coalesce(new.en_name, old.en_name), eid);
  elsif tg_table_name = 'profiles' then
    summary := coalesce(new.email, old.email) || ' ' || coalesce(old.role, 'new') || ' → ' || coalesce(new.role, old.role);
  else
    summary := eid;
  end if;
  insert into public.audit_log (actor_id, actor_email, action, entity, entity_id, summary, before_data, after_data)
  values (auth.uid(), mail, lower(tg_op), tg_table_name, eid, summary, before_j, after_j);
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

drop trigger if exists faculty_audit on public.faculty;
create trigger faculty_audit
  after insert or update or delete on public.faculty
  for each row execute function public.write_audit();

drop trigger if exists profiles_audit on public.profiles;
create trigger profiles_audit
  after insert or update or delete on public.profiles
  for each row execute function public.write_audit();

