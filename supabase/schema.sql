-- First verified signup becomes super_admin so they can approve others.

create table if not exists public.faculty (
  id integer generated by default as identity primary key,
  name text,
  title text,
  email text,
  image_url text,
  zh_name text,
  en_name text,
  title_zh text,
  title_en text,
  dept_zh text,
  dept_en text,
  edu_zh text,
  edu_en text,
  fields_zh text,
  fields_en text,
  phone text,
  site text,
  type text default 'full',
  sort_order integer default 1,
  created_at timestamptz default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'pending' check (role in ('pending', 'admin', 'super_admin', 'rejected')),
  created_at timestamptz default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role in ('admin', 'super_admin')
  );
$$;

create or replace function public.is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'super_admin'
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, role)
  values (
    new.id,
    new.email,
    case
      when not exists (select 1 from public.profiles where role = 'super_admin') then 'super_admin'
      else 'pending'
    end
  )
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

alter table public.faculty enable row level security;
alter table public.profiles enable row level security;

drop policy if exists faculty_select_public on public.faculty;
drop policy if exists faculty_insert_public on public.faculty;
drop policy if exists faculty_update_public on public.faculty;
drop policy if exists faculty_delete_public on public.faculty;
drop policy if exists faculty_insert_admin on public.faculty;
drop policy if exists faculty_update_admin on public.faculty;
drop policy if exists faculty_delete_admin on public.faculty;

create policy faculty_select_public on public.faculty for select using (true);
create policy faculty_insert_admin on public.faculty for insert with check (public.is_admin());
create policy faculty_update_admin on public.faculty for update using (public.is_admin()) with check (public.is_admin());
create policy faculty_delete_admin on public.faculty for delete using (public.is_admin());

drop policy if exists profiles_select_own on public.profiles;
drop policy if exists profiles_select_super on public.profiles;
drop policy if exists profiles_update_super on public.profiles;

create policy profiles_select_own on public.profiles for select using (auth.uid() = id);
create policy profiles_select_super on public.profiles for select using (public.is_super_admin());
create policy profiles_update_super on public.profiles for update using (public.is_super_admin()) with check (public.is_super_admin());

insert into storage.buckets (id, name, public)
values ('faculty-photos', 'faculty-photos', true)
on conflict (id) do update set public = true;

drop policy if exists faculty_photos_public_read on storage.objects;
drop policy if exists faculty_photos_admin_insert on storage.objects;
drop policy if exists faculty_photos_admin_update on storage.objects;
drop policy if exists faculty_photos_admin_delete on storage.objects;

create policy faculty_photos_public_read on storage.objects
  for select using (bucket_id = 'faculty-photos');
create policy faculty_photos_admin_insert on storage.objects
  for insert with check (bucket_id = 'faculty-photos' and public.is_admin());
create policy faculty_photos_admin_update on storage.objects
  for update using (bucket_id = 'faculty-photos' and public.is_admin())
  with check (bucket_id = 'faculty-photos' and public.is_admin());
create policy faculty_photos_admin_delete on storage.objects
  for delete using (bucket_id = 'faculty-photos' and public.is_admin());

notify pgrst, 'reload schema';
