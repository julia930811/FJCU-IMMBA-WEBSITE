create table if not exists public.faculty (
  id integer generated by default as identity primary key,
  name text,
  title text,
  email text,
  image_url text,
  zh_name text,
  en_name text,
  title_zh text,
  title_en text,
  dept_zh text,
  dept_en text,
  edu_zh text,
  edu_en text,
  fields_zh text,
  fields_en text,
  phone text,
  site text,
  type text default 'full',
  sort_order integer default 1,
  created_at timestamptz default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'pending' check (role in ('pending', 'admin', 'super_admin', 'rejected')),
  created_at timestamptz default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role in ('admin', 'super_admin')
  );
$$;

create or replace function public.is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'super_admin'
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, role)
  values (
    new.id,
    new.email,
    case
      when lower(new.email) = 'jiayiwu009@gmail.com' then 'super_admin'
      when not exists (select 1 from public.profiles where role = 'super_admin') then 'super_admin'
      else 'pending'
    end
  )
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

